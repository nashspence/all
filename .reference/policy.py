"""Check wheel custody and isolated import origins; product behavior stays local."""

import json
import stat
import subprocess
import tempfile
import zipfile
from collections.abc import Collection
from pathlib import Path, PurePosixPath


def _relative(value: str) -> str:
    path = PurePosixPath(value)
    if not value or not path.parts or "\\" in value or path.is_absolute() or ".." in path.parts or str(path) != value:
        raise ValueError("noncanonical relative artifact path")
    return value


def check_wheel_members(
    wheel: Path,
    package_roots: Collection[str],
    module_files: Collection[str] = (),
) -> None:
    roots = {_relative(root) for root in package_roots}
    modules = {_relative(module) for module in module_files}
    if not roots and not modules:
        raise ValueError("no declared import surface")
    with zipfile.ZipFile(wheel) as archive:
        entries = archive.infolist()
        names = [entry.filename for entry in entries]
        if len(names) != len(set(names)):
            raise ValueError("duplicate wheel member")
        metadata = [name for name in names if name.endswith(".dist-info/METADATA")]
        if len(metadata) != 1 or metadata[0].count("/") != 1:
            raise ValueError("expected one top-level wheel metadata record")
        metadata_root = metadata[0].removesuffix("/METADATA")
        files = set()
        for entry in entries:
            name = _relative(entry.filename.removesuffix("/") if entry.is_dir() else entry.filename)
            parts = PurePosixPath(name).parts
            if stat.S_ISLNK(entry.external_attr >> 16):
                raise ValueError("symlink wheel member")
            if "__pycache__" in parts or PurePosixPath(name).suffix.lower() in {".pyc", ".pyo"}:
                raise ValueError("generated bytecode in distribution")
            owned = (
                name == metadata_root
                or name.startswith(metadata_root + "/")
                or name in modules
                or any(name == root or name.startswith(root + "/") for root in roots)
            )
            if not owned:
                raise ValueError(f"wheel member crosses declared component boundary: {name}")
            if not entry.is_dir():
                files.add(name)
        if not modules <= files or any(not any(name.startswith(root + "/") for name in files) for root in roots):
            raise ValueError("declared import surface missing from wheel")


def probe_installed_modules(
    executable: Path,
    environment_root: Path,
    module_names: Collection[str],
) -> dict[str, str]:
    """Import owner-selected modules in an existing venv from a new empty directory.

    The owner builds/installs the artifacts. This proves only isolated import origins,
    not CLI behavior, dependency completeness for every path or native qualification.
    """
    modules = tuple(module_names)
    if not modules or len(modules) != len(set(modules)) or any(
        type(name) is not str or not all(part.isidentifier() for part in name.split("."))
        for name in modules
    ):
        raise ValueError("probe requires distinct importable module identities")
    prefix = environment_root.resolve(strict=True)
    # Preserve the venv executable's symlink path: resolving it would select base Python.
    python = executable.absolute()
    command = """
import importlib, json, sys
from pathlib import Path
names, expected, report = json.loads(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
prefix = Path(sys.prefix).resolve()
if prefix != expected or sys.prefix == sys.base_prefix:
    raise ValueError('interpreter did not select the owned virtual environment')
origins = {}
for name in names:
    module = importlib.import_module(name)
    spec = module.__spec__
    if spec is None or spec.origin in (None, 'built-in', 'frozen'):
        raise ValueError('selected module lacks an installed file origin')
    origin = Path(spec.origin).resolve(strict=True)
    if not origin.is_file() or not origin.is_relative_to(prefix):
        raise ValueError('selected module resolved outside its virtual environment')
    origins[name] = str(origin)
report.write_text(json.dumps(origins), encoding='utf-8')
"""
    with tempfile.TemporaryDirectory(prefix="installed-module-probe-") as temporary:
        report = Path(temporary) / "origins.json"
        completed = subprocess.run(
            [str(python), "-I", "-c", command, json.dumps(modules), str(prefix), str(report)],
            cwd=temporary,
            capture_output=True,
            text=True,
        )
        if completed.returncode != 0 or not report.is_file():
            raise ValueError("isolated installed-module probe refused")
        return json.loads(report.read_text(encoding="utf-8"))

